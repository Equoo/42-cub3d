#include "mat2.h"

void	mat2_invert(t_mat2 *m)
{
	float	tmp;

	tmp = m->col[0].y;
	m->col[0].y = m->col[1].x;
	m->col[1].x = tmp;
	m->col[2] = mat2_basis_xform(m, vec2_mulf(m->col[2], -1));
}