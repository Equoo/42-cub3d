#include <math.h>
#include <types/vector3.h>

t_vec3	vec3_min(t_vec3 a, t_vec3 b)
{
	a.x = fminf(a.x, b.x);
	a.y = fminf(a.y, b.y);
	a.z = fminf(a.z, b.z);
	return (a);
}
