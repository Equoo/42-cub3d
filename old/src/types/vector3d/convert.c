#include "vector3d.h"

t_vec3i	to_vec3i(t_vec3 vec)
{
	return ((t_vec3i){vec.x, vec.y, vec.z});
}

t_vec3	to_vec3(t_vec3i vec)
{
	return ((t_vec3){vec.x, vec.y, vec.z});
}
