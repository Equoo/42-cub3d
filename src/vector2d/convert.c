#include "vector2d.h"

t_vec2i	to_vec2i(t_vec2 vec)
{
	return ((t_vec2i){vec.x, vec.y});
}

t_vec2	to_vec2(t_vec2i vec)
{
	return ((t_vec2){vec.x, vec.y});
}
